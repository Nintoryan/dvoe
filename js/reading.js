export function deepPortrait(p) {
  const traits = TRAITS.map(tr => {
    const v = p[tr.k], L = lvl(v);
    return { name: tr.name, v: pct(v), L, ...tr[L] };
  });
  const style = attachStyle(p);
  const heart = { ...HEART[style], style, anx: pct(p.anx), avo: pct(p.avo), x: p.avo, y: p.anx };

  const r = [['crit', p.crit], ['contempt', p.contempt], ['defend', p.defend], ['stone', p.stone]].sort((a, b) => b[1] - a[1]);
  const riderKey = r[0][1] < 0.34 ? 'peace' : r[0][0];
  const rider = { ...RIDERS[riderKey], key: riderKey, repair: pct(p.repair), riders: r.map(([k, v]) => ({ name: RIDERS[k].name, v: pct(v) })) };

  const tv = (p.sfreq / 7 + p.simp + p.snov) / 3;
  const temper = { ...TEMPER[tv >= 0.62 ? 2 : tv >= 0.38 ? 1 : 0], v: pct(tv) };

  const curve = energyCurve(p);
  const ph = Math.round(curve.peak);
  const rhythm = { pts: curve.pts, peak: ph, energy: pct(p.energy),
    t: ph <= 10 ? 'Ты оживаешь рано. Важное — до обеда, вечер — для тишины.'
      : ph <= 13 ? 'Твоя энергия набирает силу к полудню и держится днём.'
      : ph <= 16 ? 'Ты ровный(ая): твой пик — в середине дня, без резких провалов.'
      : ph <= 19 ? 'Ты разгоняешься к вечеру. Утро для тебя — время тихого старта.'
      : 'Ты ночная птица: самые живые часы у тебя тогда, когда другие засыпают.' };

  const lt = leadTrait(p);
  const lead = { key: lt, ...LEAD_TRAITS[lt] };
  const match = {
    easy: [`По привязанности — ${EASY[style]}.`, `По ведущей черте — ${TRAIT_EASY[lt]}`],
    hard: [`По привязанности — ${HARD[style]}.`, `По ведущей черте — ${TRAIT_HARD[lt]}`],
  };
  return { traits, heart, rider, temper, rhythm, lead, match };
}
