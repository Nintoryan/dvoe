function chooseFate(c, x) {
  const minAx = Math.min(x.feel, x.everyday, x.stability, x.fidelity);
  const o = c.overallF;
  if (o > 0.66 && minAx > 0.55) return 'union';
  // тревожная судьба перебивает общую картину, только если сигнал действительно сильный
  if (x.fidelity < 0.3 && o < 0.62) return 'serpent';
  if (c.trap && x.stability < 0.5) return 'chase';
  if (x.stability < 0.34 && x.feel > 0.5) return 'storm';
  if (x.stability > 0.58 && x.feel > 0.6 && x.everyday < 0.6) return 'wings';
  if (x.feel > 0.66 && x.everyday < 0.55) return 'fire';
  if (x.feel < 0.6 && x.everyday > 0.66) return 'harbor';
  if (o > 0.6 && minAx > 0.42) return 'hearth';
  if (c.asym > 0.28 && o < 0.6) return 'moon';
  if (o < 0.4) return 'shores';
  if (x.stability < 0.32) return 'storm';
  return 'bridge';
}

export function prophecy(A, B) {
  const c = compatibility(A, B);
  // сид не зависит от соли в коде, только от содержимого — одинаков у обоих
  const seed = hashStr([A, B].map(p => JSON.stringify({ ...p, v: 0 })).sort().join('|'));
  const r = rng(seed);
  // туман: каждая ось сдвигается на ±0.07, наружу — только огрублённые значения
  const x = {};
  for (const k of Object.keys(c.axes)) x[k] = clamp(c.axes[k] + (r() - 0.5) * 0.14, 0.03, 0.97);
  c.overallF = clamp(0.27 * x.feel + 0.22 * x.everyday + 0.25 * x.stability + 0.16 * x.fidelity + 0.1 * x.family);
  const key = chooseFate(c, x);
  const fate = FATES[key];
  const nA = A.name || 'Первый', nB = B.name || 'Второй';

  // кандидаты: конкретные темы + сводные чувствительные оси
  const cand = [];
  for (const tp of TOPICS) {
    const s = tp.sig(A, B, c);
    if (s && tp[s.side]) cand.push({ kind: s.side, w: s.w + r() * 0.12, o: pick(r, tp[s.side]) });
  }
  for (const k of Object.keys(AXIS_OMENS)) {
    const d = x[k] - 0.5;
    if (Math.abs(d) < 0.1) continue;
    const side = d > 0 ? 'hi' : 'lo';
    cand.push({ kind: side, w: Math.abs(d) * 1.4 + r() * 0.12, o: pick(r, AXIS_OMENS[k][side]) });
  }
  cand.sort((a, b) => b.w - a.w);
  const strong = cand.filter(q => q.kind === 'hi').slice(0, 4);
  // на одну зону роста — минимум две сильные стороны; если сильных нет, честно покажем две зоны
  const maxGrowth = strong.length === 0 ? 2 : clamp(Math.floor(strong.length / 2), 1, 2);
  const growth = cand.filter(q => q.kind === 'lo').slice(0, maxGrowth);
  const omens = [...strong, ...growth].map(q => ({ ...q.o, kind: q.kind }));
  for (const m of MIST) { if (omens.length >= 4) break; omens.push({ ...m, kind: 'mist' }); }

  // о детях — только по сводным осям, без указания, кто чего хочет
  let children;
  if (x.family < 0.4) children = 'Настанет день, когда вы заговорите о будущем и увидите разные картины. Это развилка, которую нельзя обойти, но её можно честно пройти вдвоём.';
  else if (x.stability > 0.6) children = pick(r, [
    'Если придут дети, им достанется ваш покой. Они вырастут, зная, что любовь — это безопасно.',
    'Оракул слышит в вашем доме смех. Те, кто будет учиться любви, глядя на вас, научатся хорошему.']);
  else if (x.stability < 0.38) children = pick(r, [
    'Если придут дети, им важнее всего будет не то, ссоритесь ли вы, а то, как вы миритесь. Этому стоит научиться до них.',
    'Детям не нужны родители без ссор. Им нужны родители, которые умеют мириться у них на глазах.']);
  else children = 'Дети возможны, но не они решат вашу судьбу. Ребёнок станет зеркалом: то, что между вами недоговорено, в нём прозвучит громче.';

  const childrenWhy = x.family < 0.4
    ? 'Основа: низкая ось «Семья». Разные планы на детей — конфликт, в котором почти невозможен компромисс.'
    : 'Основа: ось «Прочность». Дети усваивают модель отношений родителей: у детей из конфликтных семей выше риск собственного развода (Amato, 1996), а умение родителей мириться этот риск снижает.';
  const winter = Math.round(clamp(c.overallF * 1.15 - 0.08, 0.04, 0.96) * 100);
  // наружу — только туманные оси, округлённые до 5
  const axes = {}; for (const k in x) axes[k] = Math.round(x[k] * 20) / 20;
  return { key, fate, axes, omens, children, childrenWhy, winter, nA, nB };
}

