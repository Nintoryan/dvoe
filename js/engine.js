/* ---------------- Ритм энергии (открытая тема) ---------------- */
export function energyCurve(p) {
  const peak = 8 + p.chrono * 3.25; // 8, 11, 14.5, 18, 21
  const amp = 0.45 + 0.55 * p.energy;
  const pts = [];
  for (let h = 6; h <= 24; h += 0.5) pts.push([h, 0.1 + amp * Math.exp(-((h - peak) ** 2) / (2 * 4 ** 2))]);
  return { peak, pts };
}
export function pairRhythm(A, B) {
  const a = energyCurve(A).pts, b = energyCurve(B).pts;
  const both = a.map(([h, v], i) => [h, Math.min(v, b[i][1])]);
  const max = Math.max(...both.map(q => q[1]));
  const win = both.filter(q => q[1] >= max * 0.75).map(q => q[0]);
  const gap = Math.abs(A.chrono - B.chrono);
  return { both, from: Math.floor(win[0]), to: Math.ceil(win[win.length - 1]), gap, strength: max };
}

/* ---------------- Чаши: кто как попадает (открытая тема) ---------------- */
function bowls(g, r) {
  let best = -1, bi = 0, miss = 0, mi = -1;
  for (let i = 0; i < 5; i++) {
    const m = Math.min(g.giv[i], r.rec[i]); if (m > best) { best = m; bi = i; }
    const d = r.rec[i] - g.giv[i]; if (d > miss) { miss = d; mi = i; }
  }
  return { pct: Math.round(cover(g, r) * 100), best: LOVE_ASPECTS[bi].t, miss: miss >= 2 ? LOVE_ASPECTS[mi].t : null };
}

