/* ---------------- Совместимость пары ---------------- */

function cover(giver, receiver) {
  // сколько естественной «отдачи» одного ложится на потребности другого
  let s = 0;
  for (let i = 0; i < 5; i++) s += Math.min(giver.giv[i], receiver.rec[i]);
  return s / 10;
}

export function compatibility(A, B) {
  const coverAB = cover(A, B); // A любит так, как нужно B
  const coverBA = cover(B, A);
  const loveAvg = (coverAB + coverBA) / 2;
  const asym = Math.abs(coverAB - coverBA);
  const touchSync = 1 - 0.125 * Math.abs(A.touch - B.touch);

  /* Открытые темы: их можно показывать прямо (без того, кто из вас какой). */
  // Притяжение — как вы попадаете друг в друга без учёта секса
  // калибровка: у случайной пары ~0.5, разброс как у остальных осей
  const attraction = clamp(0.5 + 1.4 * (
    0.5 * clamp((loveAvg - 0.25) / 0.6) + 0.14 * touchSync + 0.12 * (1 - Math.abs(A.O - B.O)) +
    0.1 * (1 - Math.abs(A.E - B.E)) + 0.14 * avg(A.A, B.A) + 0.04 - 0.73
  ));

  let hw = 0, hs = 0;
  A.habits.forEach((h, i) => { hw += HABIT_W[i]; hs += HABIT_W[i] * NEAR[Math.abs(h - B.habits[i])]; });
  const habitAgree = hs / hw;
  const comL1 = A.com.reduce((s, v, i) => s + Math.abs(v - B.com[i]), 0) / 20;
  const comfortSim = 1 - comL1;
  const everyday = clamp(0.5 + 1.9 * (
    0.44 * habitAgree + 0.22 * comfortSim + 0.12 * avg(A.C, B.C) +
    0.1 * (1 - Math.abs(A.energy - B.energy)) + 0.06 * NEAR[Math.abs(A.chrono - B.chrono)] +
    0.06 * (1 - 0.15 * Math.abs(A.sleepT - B.sleepT)) - 0.6
  ));
  const character = clamp(1 - avg(...['E', 'A', 'C', 'O'].map(k => Math.abs(A[k] - B[k]))) * 1.6);

  /* Острые темы приходят только одним грубым числом «тень» на человека (см. shadeOf).
     Слабое звено весит больше: хрупкость одного чувствуется в паре сильнее. */
  const trial = clamp(0.5 + 0.95 * (0.6 * avg(A.shade, B.shade) + 0.4 * Math.min(A.shade, B.shade) + 0.1 * avg(A.A, B.A) - 0.441));

  const kidsGap = Math.abs(A.kids - B.kids);
  const kidsBreaker = kidsGap >= 3 || (kidsGap >= 2 && (A.kids === 0 || A.kids === 4 || B.kids === 0 || B.kids === 4));
  const family = clamp(
    (1 - kidsGap / 4) * 0.55 + 0.2 * trial + 0.05 + 0.1 * NEAR[Math.abs(A.habits[3] - B.habits[3])] +
    0.1 * NEAR[Math.abs(A.habits[8] - B.habits[8])] - (kidsBreaker ? 0.2 : 0)
  );

  const overall = clamp(0.25 * attraction + 0.22 * everyday + 0.4 * trial + 0.13 * family);

  return {
    coverAB, coverBA, loveAvg, asym, habitAgree, comfortSim, kidsGap, kidsBreaker,
    axes: { attraction, everyday, trial, family, character }, overall,
  };
}

